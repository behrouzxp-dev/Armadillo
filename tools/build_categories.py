def normalize(value: str) -> str:
    canonical = value.translate(str.maketrans({"ك": "ک", "ي": "ی", "ى": "ی"}))
    return re.sub(r"\s+", " ", canonical.strip().replace("\u200c", " ").lower())


def main() -> None:
    target = ROOT / "app/src/main/assets/categories.json"
    try:
        existing_data = json.loads(target.read_text(encoding="utf-8")) if target.exists() else {}
    except (json.JSONDecodeError, OSError) as error:
        raise SystemExit(f"Could not safely read existing topic bank: {error}")

    data: dict[str, dict[str, list[str]]] = {}
    seen: dict[str, tuple[str, str]] = {}
    failed = False

    def add_category(category: str, levels: dict[str, list[str]]) -> None:
        nonlocal failed
        data[category] = {}
        for level in LEVELS:
            words = levels.get(level, [])
            if len(words) != EXPECTED_EACH:
                print(f"FAIL {category} level {level}: expected {EXPECTED_EACH}, found {len(words)}")
                failed = True
            local: set[str] = set()
            for word in words:
                key = normalize(word)
                if key in local:
                    print(f"FAIL duplicate within {category} level {level}: {word}")
                    failed = True
                local.add(key)
                if key in seen:
                    print(f"FAIL duplicate across topic bank: {word!r} and {seen[key][1]!r} ({seen[key][0]})")
                    failed = True
                else:
                    seen[key] = (f"{category}.{level}", word)
            data[category][level] = words
            print(f"{category} level {level}: {len(words)} words")

    for category, source_levels in GROUPS.items():
        parsed = {
            level: [line.strip() for line in source.strip().splitlines() if line.strip()]
            for level, source in source_levels.items()
        }
        add_category(category, parsed)

    # Preserve the manually curated additions so rerunning this generator never silently
    # removes either Armadillo category. Regenerate those lists with add_armadillo_categories.py.
    for category in ("places", "technology"):
        saved_levels = existing_data.get(category)
        if not isinstance(saved_levels, dict):
            print(f"FAIL missing {category}; restore it with tools/add_armadillo_categories.py before writing")
            failed = True
            continue
        add_category(category, saved_levels)

    if len(seen) != 1500:
        print(f"FAIL playable topic bank: expected 1500 distinct words, found {len(seen)}")
        failed = True
    if failed:
        raise SystemExit(1)
    target.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(seen)} distinct topic words to {target}")


if __name__ == "__main__":
    main()
